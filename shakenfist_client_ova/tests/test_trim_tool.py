def _comment(original):
    return ('<!-- Trimmed from %s (SHA-256 %s of the original descriptor) by tools/trim-ovf-descriptor.py; '
            'prose replaced with "TRIMMED". -->' % (SOURCE, hashlib.sha256(original).hexdigest()))


def _replace_once(text, old, new):
    if text.count(old) != 1:
        raise AssertionError('%r occurs %d times' % (old, text.count(old)))
    return text.replace(old, new)


class TrimTestCase(testtools.TestCase):
    def setUp(self):
        super(TrimTestCase, self).setUp()
        self.original = OVF1.encode('utf-8')
        self.trimmed = tool.trim(self.original, SOURCE)

    def test_whole_output(self):
        # Every change the tool makes, made by hand: anything else in the
        # output must be the original's bytes.
        expected = OVF1.replace(DECLARATION, DECLARATION + '\n' + _comment(self.original), 1)
        for old, new in (
                ('<Description>Secret system description</Description>', '<Description>TRIMMED</Description>'),
                ('<Info>Secret product blurb</Info>', '<Info>TRIMMED</Info>'),
                ('<Product>Secret Product</Product>', '<Product>TRIMMED</Product>'),
                ('<Vendor>Secret Vendor &amp; Sons</Vendor>', '<Vendor>TRIMMED</Vendor>'),
                ('<Label>Secret label</Label>', '<Label>TRIMMED</Label>'),
                ('note="1 > 0">Secret property description</Description>', 'note="1 > 0">TRIMMED</Description>'),
                ('<License><!-- a comment first -->Secret licence text</License>', '<License>TRIMMED</License>'),
                ('<Annotation><![CDATA[Secret <annotation>]]></Annotation>', '<Annotation>TRIMMED</Annotation>'),
                ('<Msg ovf:msgid="description">Geheime Beschreibung</Msg>',
                 '<Msg ovf:msgid="description">TRIMMED</Msg>')):
            expected = _replace_once(expected, old, new)
        machine_start = expected.index('<vbox:Machine')
        machine_end = expected.index('</vbox:Machine>') + len('</vbox:Machine>')
        expected = (expected[:machine_start] + '<vbox:Machine ovf:required="false" version="1.16-linux"/>'
                    + expected[machine_end:])
        self.assertEqual(expected, self.trimmed.decode('utf-8'))

    def test_prose_replaced(self):
        for secret in SECRETS:
            self.assertNotIn(secret.encode('utf-8'), self.trimmed)
        for element in ('Product', 'Vendor', 'Label', 'License', 'Annotation'):
            self.assertIn(('<%s>TRIMMED</%s>' % (element, element)).encode('utf-8'), self.trimmed)

    def test_empty_prose_left_alone(self):
        self.assertIn(b'<FullVersion/>', self.trimmed)
        self.assertIn(b'<ProductUrl></ProductUrl>', self.trimmed)

    def test_structural_descriptions_untouched(self):
        self.assertIn(b'<Description>The nat network</Description>', self.trimmed)
        self.assertIn(b'<Description>Ubuntu 64-bit</Description>', self.trimmed)
        self.assertIn(b'<rasd:Description>Number of Virtual CPUs</rasd:Description>', self.trimmed)
        self.assertIn(b'<Info>A virtual machine</Info>', self.trimmed)
        self.assertIn(b'<Info>The kind of installed guest operating system</Info>', self.trimmed)

    def test_machine_emptied(self):
        self.assertIn(b'    <vbox:Machine ovf:required="false" version="1.16-linux"/>\n  </VirtualSystem>',
                      self.trimmed)
        self.assertNotIn(b'snapshotFolder', self.trimmed)
        self.assertNotIn(b'SharedFolder', self.trimmed)

    def test_both_envelope_declarations_kept(self):
        self.assertIn(b'<Envelope xmlns="http://schemas.dmtf.org/ovf/envelope/1" '
                      b'xmlns:ovf="http://schemas.dmtf.org/ovf/envelope/1"', self.trimmed)

    def test_comments_survive(self):
        self.assertIn(b'?>\n<!-- Trimmed from ', self.trimmed)
        self.assertIn(b'-->\n<!-- Generated by VMware ovftool -->\n<Envelope', self.trimmed)
        self.assertIn(b'<!-- a comment inside the root -->', self.trimmed)

    def test_comment_in_prose_is_trimmed(self):
        self.assertNotIn(b'a comment first', self.trimmed)

    def test_xsi_type_only_prefix_survives(self):
        self.assertIn(b'xmlns:cim="http://schemas.dmtf.org/wbem/wscim/1/common"', self.trimmed)
        self.assertIn(b'xsi:type="cim:cimString"', self.trimmed)

    def test_provenance_comment(self):
        expected = DECLARATION + '\n' + _comment(self.original) + '\n<!-- Generated'
        self.assertTrue(self.trimmed.decode('utf-8').startswith(expected))

    def test_check_passes(self):
        descriptor = tool.check(self.original, self.trimmed)
        kinds = [span.kind for span in descriptor.spans]
        self.assertEqual(9, kinds.count('prose'))
        self.assertEqual(1, kinds.count('emptied'))

    def test_trim_is_deterministic(self):
        self.assertEqual(self.trimmed, tool.trim(self.original, SOURCE))


class CheckFailureTestCase(testtools.TestCase):
    def setUp(self):
        super(CheckFailureTestCase, self).setUp()
        self.original = OVF1.encode('utf-8')
        self.trimmed = tool.trim(self.original, SOURCE)

    def _assert_fails_at(self, trimmed, offset, element=None):
        e = self.assertRaises(tool.CheckError, tool.check, self.original, trimmed)
        self.assertEqual(offset, e.offset)
        self.assertIn('offset %d ' % offset, str(e))
        if element is not None:
            self.assertEqual(element, e.element)
        return e

    def test_byte_outside_span_changed(self):
        position = self.trimmed.index(b'logical networks') + len(b'logical netw')
        changed = self.trimmed[:position] + b'e' + self.trimmed[position + 1:]
        self._assert_fails_at(changed, position, '/Envelope/NetworkSection/Info')

    def test_byte_in_prolog_changed(self):
        position = self.trimmed.index(b'ovftool')
        changed = self.trimmed[:position] + b'O' + self.trimmed[position + 1:]
        self._assert_fails_at(changed, position, '(outside the root element)')

    def test_prose_not_trimmed(self):
        changed = self.trimmed.replace(b'<Vendor>TRIMMED</Vendor>', b'<Vendor>Secret Vendor</Vendor>')
        position = changed.index(b'Secret Vendor')
        e = self._assert_fails_at(changed, position, '/Envelope/VirtualSystem/ProductSection/Vendor')
        self.assertIn('not "TRIMMED"', e.reason)

    def test_prose_placeholder_altered(self):
        changed = self.trimmed.replace(b'<Label>TRIMMED</Label>', b'<Label>TRIMMED!</Label>')
        self._assert_fails_at(changed, changed.index(b'TRIMMED!'))

    def test_prose_emptied_instead_of_trimmed(self):
        changed = self.trimmed.replace(b'<Product>TRIMMED</Product>', b'<Product></Product>')
        self.assertRaises(tool.CheckError, tool.check, self.original, changed)

    def test_machine_keeps_forbidden_attribute(self):
        changed = self.trimmed.replace(
            b'<vbox:Machine ovf:required="false" version="1.16-linux"/>',
            b'<vbox:Machine ovf:required="false" version="1.16-linux" name="secret-vm"/>')
        e = self._assert_fails_at(changed, changed.index(b' name="secret-vm"'),
                                  '/Envelope/VirtualSystem/vbox:Machine')
        self.assertIn('name', e.reason)

    def test_machine_keeps_children(self):
        changed = self.trimmed.replace(
            b'<vbox:Machine ovf:required="false" version="1.16-linux"/>',
            b'<vbox:Machine ovf:required="false" version="1.16-linux"><Hardware/></vbox:Machine>')
        self._assert_fails_at(changed, changed.index(b'<Hardware/>'))

    def test_machine_attribute_value_changed(self):
        changed = self.trimmed.replace(b'version="1.16-linux"/>', b'version="1.17-linux"/>')
        self._assert_fails_at(changed, changed.index(b'1.17') + 3)

    def test_wrong_digest(self):
        digest = hashlib.sha256(self.original).hexdigest().encode('ascii')
        changed = self.trimmed.replace(digest, b'0' * 64)
        self._assert_fails_at(changed, changed.index(b'0' * 64))

    def test_missing_comment(self):
        start = self.trimmed.index(b'\n<!-- Trimmed')
        end = self.trimmed.index(b'-->', start) + 3
        self.assertRaises(tool.CheckError, tool.check, self.original, self.trimmed[:start] + self.trimmed[end:])

    def test_untrimmed_copy(self):
        # The original itself is not a trimmed copy of the original.
        self.assertRaises(tool.CheckError, tool.check, self.original, self.original)


