def _load_tool():
    # The tool is a script with a hyphenated name outside the package, so it
    # is loaded from its path rather than imported.
    spec = importlib.util.spec_from_file_location('trim_ovf_descriptor', TOOL_PATH)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


tool = _load_tool()

